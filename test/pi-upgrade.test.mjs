import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { BACKGROUND_CONTEXT as context } from "@earendil-works/chord/context";
import { createModels, Type } from "@earendil-works/pi-ai";
import {
  Harness,
  createRegistry,
  defineExtension,
  defineTool,
} from "@earendil-works/pi-durable";
import { openNodeSqliteStorage } from "@earendil-works/pi-durable/storage/sqlite/node";
import { PINNED_DOCS } from "../src/skill-docs.ts";

const json = (path) =>
  JSON.parse(readFileSync(new URL(path, import.meta.url), "utf8"));

test("Pi packages, lockfile and installed documentation stay exactly aligned", () => {
  const manifest = json("../package.json");
  const lock = json("../package-lock.json");
  for (const name of ["chord", "pi-ai", "pi-durable"]) {
    const pkg = `@earendil-works/${name}`;
    assert.equal(manifest.dependencies[pkg], "1.3.0");
    assert.equal(lock.packages[""].dependencies[pkg], "1.3.0");
    assert.equal(lock.packages[`node_modules/${pkg}`].version, "1.3.0");
    assert.equal(json(`../node_modules/${pkg}/package.json`).version, "1.3.0");
  }
  const readme = readFileSync(
    new URL(
      "../node_modules/@earendil-works/pi-durable/README.md",
      import.meta.url,
    ),
    "utf8",
  );
  assert.equal(PINNED_DOCS[0].version, "1.3.0");
  assert.equal(PINNED_DOCS[0].content, readme);
  assert.equal(
    PINNED_DOCS[0].sha256,
    createHash("sha256").update(readme).digest("hex"),
  );
});

test(
  "real 1.1.0 SQLite reopens on 1.3.0 and migrates tools without replaying unsafe work",
  { timeout: 10000 },
  async () => {
    // Generated by the real 1.1.0 harness, containing only synthetic tool calls.
    const fixture = json("./fixtures/pi-durable-1.1.0.json");
    const dir = mkdtempSync(join(tmpdir(), "red-pi-upgrade-"));
    const path = join(dir, "pi.sqlite");
    const db = new DatabaseSync(path);
    db.exec(fixture.sql);
    db.close();
    let executions = 0;
    const registry = createRegistry();
    registry.install(
      defineExtension({
        name: "upgrade-fixture",
        tools: [
          defineTool({
            name: "fixture",
            parameters: Type.Object({}),
            description: "Synthetic fixture only",
            replay: "unsafe",
            execute: async () => {
              executions++;
              return {
                output: [{ type: "text", text: "Synthetic upgrade output" }],
              };
            },
          }),
        ],
      }),
    );
    let harness;
    try {
      harness = await Harness.open(
        await openNodeSqliteStorage(path),
        { models: createModels(), registry },
        context,
      );
      await harness.waitForIdle(context);
      assert.equal(executions, 1, "only the never-started task may execute");
      for (const id of [fixture.ids.pending, fixture.ids.interrupted]) {
        const task = await harness.getTask(id, context);
        assert.equal(task.version, 2);
        assert.equal(task.input.kind, "model");
        assert.equal(task.state.status, "terminal");
        assert.equal(
          task.state.outcome.status,
          id === fixture.ids.pending ? "completed" : "failed",
        );
        const result = await harness.commit(
          (tx) => tx.entry(task.state.outcome.result.entryId),
          context,
        );
        const text = JSON.stringify(result.model);
        if (id === fixture.ids.pending)
          assert.match(text, /Synthetic upgrade output/);
        else assert.match(text, /interrupted/);
      }
      await harness.close(context);
      harness = await Harness.open(
        await openNodeSqliteStorage(path),
        { models: createModels(), registry },
        context,
      );
      await harness.waitForIdle(context);
      assert.equal(executions, 1, "reopen must not repeat completed tool work");
      const original = await harness.commit(
        (tx) => tx.entry(fixture.ids.assistant),
        context,
      );
      assert.equal(original.model[0].content[0].id, "legacy-call");
    } finally {
      await harness?.close(context);
      rmSync(dir, { recursive: true, force: true });
    }
  },
);
